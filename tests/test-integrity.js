/* ── Judge path ──────────────────────────────────────────────────────────────
   The brief's constraint is a ~90–120 second in-app path supporting a
   three-minute video. That is a checkable property, so it is checked: if a step
   is added or a duration edited, the suite says whether the path still fits. */
suite('Judge path fits the demo window and drives the real UI');
{
  const jpCtx = {
    console,
    window: { matchMedia: () => ({ matches: false }) },
    document: { getElementById: () => null, querySelector: () => null,
                querySelectorAll: () => [], createElement: () => ({}),
                addEventListener: () => {}, body: { classList: { add(){}, remove(){} } } },
    escapeHtml: s => String(s), setTimeout, clearTimeout,
  };
  const vm2 = require('vm');
  vm2.createContext(jpCtx);
  vm2.runInContext(fs.readFileSync(path.join(ROOT, 'js', 'judge-path.js'), 'utf8'), jpCtx);
  const PATH  = vm2.runInContext('JUDGE_PATH', jpCtx);
  const total = vm2.runInContext('judgePathTotalSeconds()', jpCtx);

  ok(total >= 90 && total <= 120,
     `the path runs ${total}s — inside the 90-120s window a 3-minute video allows`);
  ok(PATH.length >= 6 && PATH.length <= 9,
     `the path has ${PATH.length} steps — enough to tell the story, few enough to stay a story rather than a feature tour`);

  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const js   = readAll('js', '.js').map(f => f.text).join('\n');
  for (const s of PATH) {
    ok(typeof s.title === 'string' && s.title.length > 8, `step "${s.id}" has a title`);
    ok(typeof s.body === 'string' && s.body.length > 60, `step "${s.id}" says something substantive`);
    ok(s.seconds >= 8 && s.seconds <= 25, `step "${s.id}" is paced between 8 and 25 seconds (${s.seconds}s)`);
    ok(['overview','analyze','science','mapcompare','bioenergy'].includes(s.page),
       `step "${s.id}" targets a real page (${s.page})`);
    if (s.target) {
      // The selector must exist somewhere the app can actually produce it —
      // static markup, or a renderer that emits it. A step pointing at nothing
      // would narrate over an empty screen.
      const bare = s.target.replace(/^[#.]/, '');
      ok(html.includes(bare) || js.includes(bare),
         `step "${s.id}" targets "${s.target}", which the app actually renders`);
    }
  }
  const ids = PATH.map(s => s.id);
  for (const required of ['problem','measure','stress','why','confidence','biology','unknown'])
    ok(ids.includes(required), `the path includes the "${required}" beat of the pipeline story`);

  // It replaced the old cosmetic toggle — there must be exactly one definition.
  const defs = readAll('js', '.js').filter(f => /function toggleJudgeMode/.test(f.text)).map(f => f.name);
  eq(defs, ['js/judge-path.js'], 'toggleJudgeMode is defined once, in judge-path.js');
  ok(!/function toggleJudgeMode/.test(html), 'and not redefined inline in index.html');
}

/* ── Heating value: the string-destructure regression ─────────────────────────
   `heatingValueRange` in SCAN_PLANTS is PROSE ('17–19 MJ/kg dry'), not a tuple.
   A previous build destructured it as `const [lo, hi] = plant.heatingValueRange`,
   which takes the first two CHARACTERS: switchgrass displayed "1.0–7.0 GJ/t"
   against a real 17–19, attributed to literature. These assertions pin both the
   parse and the physics. */
suite('Heating values parse from prose and are never scaled by photo observations');
{
  const scannerSrc = fs.readFileSync(path.join(ROOT, 'js', 'scanner.js'), 'utf8');

  ok(!/const\s*\[\s*hvLow\s*,\s*hvHigh\s*\]\s*=\s*plant\.heatingValueRange/.test(scannerSrc),
     'heatingValueRange is never array-destructured directly off the profile string');

  const m = scannerSrc.match(/function parseHeatingValueRange[\s\S]*?\n}/);
  ok(!!m, 'parseHeatingValueRange exists');
  const parseHeatingValueRange = new Function(m[0] + '; return parseHeatingValueRange;')();

  eq(parseHeatingValueRange('17–19 MJ/kg dry'), { low: 17, high: 19 },
     'switchgrass parses to 17-19, not 1-7');
  eq(parseHeatingValueRange('14–17 MJ/kg dry (bagasse)'), { low: 14, high: 17 },
     'a parenthetical qualifier does not leak into the numbers');
  eq(parseHeatingValueRange('Not applicable'), { low: null, high: null },
     'non-numeric entries yield null rather than a fabricated range');

  const ranges = [...scannerSrc.matchAll(/heatingValueRange:'([^']+)'/g)].map(x => x[1]);
  ok(ranges.length >= 30, `all ${ranges.length} plant profiles are covered`);
  const numeric = ranges.map(parseHeatingValueRange).filter(r => r.low != null);
  ok(numeric.length > 0, 'at least some profiles carry a numeric range');
  ok(numeric.every(r => r.low >= 5 && r.high <= 45),
     'every parsed heating value is physically plausible for dry biomass (5-45 GJ/t)');
  ok(numeric.every(r => r.low <= r.high), 'every parsed range is ordered low <= high');

  /* Heating value is energy per unit DRY mass. Canopy density and patch size
     change standing stock, not energy density, so they must not multiply it. */
  const fnBody = scannerSrc.match(/function estimateBiomassEnergyRange[\s\S]*?\n}/)[0];
  ok(!/hvLow\s*\*/.test(fnBody) && !/hvHigh\s*\*/.test(fnBody),
     'the heating value is never multiplied by a photo-derived modifier');
  ok(!/Modifier formula:/.test(scannerSrc),
     'no "Modifier formula:" is rendered for a relationship that does not exist');
}

/* ── Renamed things stay renamed ──────────────────────────────────────────────
   Two renames shipped half-done: a find-and-replace was written against markup
   that did not exist ("<strong>Bioenergy Scanner</strong> tab" vs the actual
   plain-text "Bioenergy Scanner tab"), so it silently matched nothing and the
   stale name went live. These assertions fail on the OLD name directly, so a
   replace that misses can no longer pass unnoticed. */
suite('Retired feature names do not survive anywhere on a shipping surface');
{
  const RETIRED_NAMES = [
    ['Bioenergy Scanner',        'Field Observation Mode'],
    ['Survival Score',           'Environmental Tolerance Match'],
    ['Bioenergy Confidence Score','Bioenergy Suitability Index'],
    ['Plant-to-Fuel Scanner',    'Field Observation Mode'],
  ];
  /* claims-registry.js and bioenergy-engine.js quote the old names on purpose:
     that is the correction being published, not the name being used. */
  const SURFACES = UI_SOURCES.filter(s => !/bioenergy-engine/.test(s.name));
  for (const [oldName, newName] of RETIRED_NAMES) {
    /* A rename NOTE is not a USE. "formerly X" and "previously called X" are
       the correction being published to the reader; only a bare occurrence
       means the old name is still in service. */
    const MARKERS = ['formerly ', 'previously called the ', 'previously called ',
                     'RENAMED from "', 'renamed from '];
    const stripNotes = txt => MARKERS.reduce((s, m) => s.split(m + oldName).join(''), txt);
    const hits = SURFACES.filter(s => stripNotes(s.text).includes(oldName)).map(s => s.name);
    eq(hits, [], `"${oldName}" is gone (renamed to "${newName}")`);
  }
}

