suite('Retired claims do not survive anywhere in the UI');
const BANNED = [
  // Match the NUMBERS, not number-plus-unit adjacency. The earlier patterns
  // required "6–14 gallons of water" and "200–280 GJ", so the same claims
  // survived in the UI written as "6–14 gal/gal fuel" and as a table row whose
  // value and unit sat in different object fields. A hostile review found both
  // still rendering. These patterns look for the figures themselves.
  [/98\s*%?\s*less water/i,               '"98% less water" (unsourced, boundary-dependent)'],
  [/\b784\b/,                             'the 784 gal/gal corn-ethanol water figure'],
  [/\b6\s*[–—-]\s*14\b/,                 'the "6–14" cellulosic water figure'],
  [/\b200\s*[–—-]\s*280\b/,              '"200–280 GJ/ha/yr" misattributed to Schmer et al.'],
  [/\b120\s*[–—-]\s*160\b/,              '"120–160 GJ/ha/yr" corn comparison not in the cited source'],
  [/Survival Score/i,                     '"Survival Score" (implies a survival probability)'],
  [/Survival Chance/i,                    '"Survival Chance" (an explicit persistence probability)'],
  [/Productivity Score/i,                 '"Productivity Score" (implies a measured yield)'],
  [/Bioenergy Confidence Score/i,         '"Bioenergy Confidence Score" (conflates suitability with confidence)'],
  [/genes activated by/i,                 '"genes activated by" (implies expression was measured)'],
  [/wet[- ]bulb sensor/i,                 'the claim that VPD needs a wet-bulb sensor'],
  [/Drought Memory/i,                     '"Drought Memory" (implies measured plant drought)'],
  // AI overclaims. There is no LLM and no generative model anywhere in this app.
  [/AI[- ]generated/i,                    '"AI-generated" (nothing in this app is generated by a model)'],
  [/AI[- ]assisted/i,                     '"AI-assisted" (no model assists any computation)'],
  [/AI prototype/i,                       '"AI prototype estimates"'],
  [/AI Intelligence/i,                    '"AI Intelligence" branding'],
  [/visual AI analysis/i,                 '"visual AI analysis"'],
  [/\bAI Assistant\b/i,                   '"AI Assistant" (it is rule-based intent matching)'],
  // Calibration is claimed nowhere, because nothing is calibrated.
  [/calibrated to (?:published|the)/i,    'a claim that a model is calibrated to literature'],
];
/* A retired claim may legitimately appear inside a DOCUMENTED CORRECTION —
   we deliberately quote the old wording so the fix is auditable rather than
   quietly erased. Those contexts are recognised by an explicit marker. Any
   other occurrence is a real violation. */
/* A retired claim may appear inside a DOCUMENTED CORRECTION — the old wording
   is quoted deliberately so the fix is auditable. Markers are deliberately
   specific: an earlier version whitelisted the phrase "no longer", which is
   common enough to excuse a real violation by accident. */
const CORRECTION_MARKER = /previously (claimed|gave|showed|stated|read|contained|called|described|presented|branded|labelled|labeled)|Withdrawn|RENAMED from|correction we made|We removed|this (?:card|table|answer|page|banner) previously|has been (?:removed|withdrawn|corrected)|TC_RETIRED_CLAIMS|retired claim|over-?correct\w*|(?:was|is) (?:itself )?false|overshot|Rewritten to/i;
function offendingOccurrences(text, re) {
  const g = new RegExp(re.source, re.flags.includes('g') ? re.flags : re.flags + 'g');
  const out = [];
  let m;
  while ((m = g.exec(text))) {
    const window = text.slice(Math.max(0, m.index - 320), m.index + 320);
    if (!CORRECTION_MARKER.test(window)) out.push(m.index);
    if (m.index === g.lastIndex) g.lastIndex++;
  }
  return out;
}
for (const [re, label] of BANNED) {
  const hits = UI_SOURCES.filter(s => offendingOccurrences(s.text, re).length > 0).map(s => s.name);
  ok(hits.length === 0, `no UI file states ${label} outside a documented correction${hits.length ? ' — found in ' + hits.join(', ') : ''}`);
}

suite('AI claims are accurate in BOTH directions');
{
  /* Over-claiming is caught by the BANNED list above. Under-claiming needs its
     own check: while removing inflated AI branding, several pages went on to
     assert that no AI is used anywhere — which is false, because Field
     Observation Mode runs a real MobileNet classifier. A denial is as
     inaccurate as an inflated claim, so both directions are policed. */
  const DENIALS = [/no AI is used anywhere/i, /there is no AI anywhere/i,
                   /no AI is involved anywhere/i, /No AI is involved at any point/i,
                   /performs no computer vision/i, /no image analysis (?:takes place|is performed)/i];
  for (const re of DENIALS) {
    const hits = UI_SOURCES.filter(s => re.test(s.text)).map(s => s.name);
    ok(hits.length === 0,
       `no file denies AI outright with ${re.source} — a real MobileNet classifier runs in Field Observation Mode${hits.length ? ' — found in ' + hits.join(', ') : ''}`);
  }
  // And the classifier must be described where it is used.
  const scanner = SOURCES.find(s => s.name === 'index.html');
  ok(/MobileNet/i.test(scanner.text), 'the interface names the classifier it actually runs');
  ok(/ImageNet/i.test(scanner.text),
     'and states that its confidence is an ImageNet class probability, not a species probability');
}

